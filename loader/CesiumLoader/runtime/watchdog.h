// watchdog.h - 主线程停滞看门狗(原生, 不依赖 mod/托管代码)
//
// 为什么需要它:
//   卡死(死锁/主线程被阻塞)不产生任何异常, 加载器的崩溃处理器永远不会被触发,
//   现场只剩"游戏无响应"。托管侧也救不了——真正的托管卡死里, mod 自己的线程同样可能死掉。
//   所以看门狗放在原生层: 每秒采样一次主线程的 Rip/Rsp, 连续 timeout 秒不变就主动写一份
//   hang dump(与崩溃转储同一套设施, 见 crashdump.h 的 write_dump_now)。
//
// 判据与边界:
//   - 只认"指令指针不动"。主线程在动但不出帧(反复调用/空转)抓不到 —— 那类由 mod 心跳补;
//   - 窗口不在前台时**不判定**(玩家切出去/游戏被挂起时主线程本来就可能停住), 并把停滞起点重置;
//   - 启动后先等 warmup(20s), 避开 shader 编译/Addressables 首次加载这类长帧;
//   - 同一段停滞只落一次盘; 主线程重新移动后才可能再次落盘;
//   - 每次采样只暂停主线程几微秒(1 Hz), 稳态开销可以忽略。
//
// 主线程识别: 进程内**创建时间最早**的线程就是主线程(Windows 上由加载器最先创建)。
// 这是唯一不依赖 Unity 版本信息的判据; 拿不到就 fail-open, 只记日志。
#pragma once

namespace cesium::watchdog
{

// 启动看门狗(幂等)。timeout_sec 建议 20–60: 小于 10 秒容易撞上加载画面。
// 失败(找不到主线程/线程打不开)只记日志, 不影响游戏启动。
void start(unsigned timeout_sec);

} // namespace cesium::watchdog
